-- Partnership registry: a safety verification record is not sufficient proof
-- that a merchant has authorised Visit 1MY to distribute a commercial offer.
create sequence if not exists public.reward_partner_code_seq start 1;

create table if not exists public.reward_partners (
  id uuid primary key default gen_random_uuid(),
  partner_code text not null default (
    'MCH-' || lpad(nextval('public.reward_partner_code_seq')::text, 6, '0')
  ),
  legal_name text not null,
  display_name text not null,
  registration_number text,
  category text not null default 'Other',
  contact_email text,
  contact_phone text,
  website_url text,
  verification_status text not null default 'pending'
    check (verification_status in ('pending', 'verified', 'rejected', 'suspended')),
  verification_notes text,
  verified_by uuid references public.admin_accounts(id) on delete set null,
  verified_at timestamptz,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists reward_partners_partner_code_key
  on public.reward_partners(partner_code);
create unique index if not exists reward_partners_legal_name_key
  on public.reward_partners(lower(btrim(legal_name)));
create unique index if not exists reward_partners_registration_number_key
  on public.reward_partners(lower(btrim(registration_number)))
  where nullif(btrim(registration_number), '') is not null;

alter table public.reward_vouchers
  add column if not exists partner_id uuid
  references public.reward_partners(id) on delete restrict;

insert into public.reward_partners (
  legal_name, display_name, category, verification_status,
  verification_notes, verified_at
)
select distinct
  btrim(rv.partner_name), btrim(rv.partner_name), 'Legacy sponsor', 'verified',
  'Migrated from an existing published Module 5 reward. Revalidate the commercial agreement.',
  now()
from public.reward_vouchers rv
where nullif(btrim(rv.partner_name), '') is not null
on conflict do nothing;

