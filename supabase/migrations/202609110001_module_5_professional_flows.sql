create or replace function public.enforce_reward_partner_policy()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  partner_ok boolean;
begin
  select rp.is_active and rp.verification_status = 'verified'
  into partner_ok
  from public.reward_partners rp
  where rp.id = new.partner_id;

  if (new.status = 'published' or coalesce(new.is_active, false))
     and coalesce(partner_ok, false) is not true then
    raise exception 'Only an active, verified reward partner can sponsor a voucher';
  end if;

  select rp.display_name into new.partner_name
  from public.reward_partners rp
  where rp.id = new.partner_id;
  return new;
end;
$$;

drop trigger if exists reward_voucher_partner_policy
  on public.reward_vouchers;
create trigger reward_voucher_partner_policy
before insert or update of partner_id, status, is_active
on public.reward_vouchers
for each row execute function public.enforce_reward_partner_policy();

create or replace function public.stamp_reward_partner_verification()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' and new.verification_status = 'verified' then
    new.verified_by := auth.uid();
    new.verified_at := now();
  elsif tg_op = 'UPDATE'
        and new.verification_status = 'verified'
        and old.verification_status is distinct from 'verified' then
    new.verified_by := auth.uid();
    new.verified_at := now();
  elsif new.verification_status <> 'verified' then
    new.verified_by := null;
    new.verified_at := null;
  end if;
  return new;
end;
$$;

drop trigger if exists reward_partner_verification_stamp
  on public.reward_partners;
create trigger reward_partner_verification_stamp
before insert or update of verification_status on public.reward_partners
for each row execute function public.stamp_reward_partner_verification();

create or replace function public.archive_unverified_partner_vouchers()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.is_active is not true or new.verification_status <> 'verified' then
    update public.reward_vouchers
    set status = 'archived', is_active = false, updated_at = now()
    where partner_id = new.id and (status <> 'archived' or is_active = true);
  end if;
  return new;
end;
$$;

drop trigger if exists reward_partner_voucher_archive
  on public.reward_partners;
create trigger reward_partner_voucher_archive
after update of verification_status, is_active on public.reward_partners
for each row execute function public.archive_unverified_partner_vouchers();

